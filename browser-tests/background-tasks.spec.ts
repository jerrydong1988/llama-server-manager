import { expect, test, type Page } from '@playwright/test'

async function openTasks(page: Page) {
  await page.addInitScript(() => { localStorage.setItem('lang', 'zh-CN'); localStorage.setItem('lastTab', 'instances') })
  await page.goto('/')
  await page.getByRole('button', { name: '任务中心', exact: true }).click()
  await page.getByRole('tab', { name: '后台任务', exact: true }).click()
  await expect(page.getByTestId('task-task-queued')).toBeVisible()
}
test.afterEach(async ({ page }) => { await expect(page.locator('html')).toHaveAttribute('data-tauri-mock-unhandled', '[]') })

test('shared task states, results, filters and safe queued cancellation', async ({ page }, testInfo) => {
  await openTasks(page)
  const detail = page.getByTestId('task-detail')
  await page.getByTestId('task-task-succeeded').click()
  await expect(detail.getByRole('region', { name: '执行结果' })).toContainText('"models": 28')
  await expect(detail.locator('script')).toHaveCount(0)
  await expect(detail.getByRole('button', { name: '取消排队任务' })).toBeDisabled()
  await page.getByTestId('task-task-failed').click()
  await expect(detail).toContainText('scan unavailable')
  await expect(detail).toContainText('可重试: 是')
  await page.getByTestId('task-task-interrupted').click()
  await expect(detail).toContainText('操作可能已生效')
  await page.getByTestId('task-task-running').click()
  await expect(detail.getByRole('button', { name: '取消排队任务' })).toBeDisabled()
  await page.getByTestId('task-task-queued').click()
  await detail.getByRole('button', { name: '取消排队任务' }).click()
  await expect(detail.getByRole('status')).toHaveText('任务已在执行前取消。')
  await expect(detail).toContainText('CANCELLED')
  await expect(page.getByTestId('task-task-queued')).toContainText('已取消')
  expect(await page.evaluate(() => window.__TAURI_BROWSER_TEST__.calls.filter(c => c.command === 'cancel_management_task').map(c => c.payload))).toEqual([{ id: 'task-queued' }])
  await page.getByRole('combobox', { name: '任务状态' }).selectOption('cancelled')
  await expect(page.getByTestId('background-tasks')).toContainText('2 / 6 条记录')
  await page.getByRole('textbox', { name: '搜索操作名称或任务 ID' }).fill('nonexistent')
  await expect(page.getByText('没有符合筛选条件的任务。')).toBeVisible()
  await page.getByRole('textbox', { name: '搜索操作名称或任务 ID' }).fill('')
  await page.getByRole('combobox', { name: '任务状态' }).selectOption('')
  await page.getByRole('dialog').screenshot({ path: testInfo.outputPath('background-tasks-dark.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '切换到明亮模式' }).click()
  await page.getByRole('button', { name: '任务中心', exact: true }).click()
  await expect(page.getByRole('tab', { name: '后台任务' })).toHaveAttribute('aria-selected', 'true')
  await page.setViewportSize({ width: 860, height: 800 })
  await page.getByRole('dialog').screenshot({ path: testInfo.outputPath('background-tasks-light-narrow.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

for (const status of ['running', 'succeeded']) test(`cancellation racing ${status} shows the actual backend state`, async ({ page }) => {
  await openTasks(page)
  await page.evaluate(s => window.__MANAGEMENT_TASK_TEST__.race(s), status)
  await page.getByTestId('task-detail').getByRole('button', { name: '取消排队任务' }).click()
  await expect(page.getByTestId('task-detail')).toContainText(status === 'running' ? '任务已开始执行，无法在此取消。' : '任务已先于取消请求结束')
  await expect(page.getByTestId('task-detail').getByRole('button', { name: '取消排队任务' })).toBeDisabled()
  await expect(page.getByTestId('task-task-queued')).toContainText(status === 'running' ? '执行中' : '成功')
})

test('polling updates external tasks, recovers errors and ignores stale detail responses', async ({ page }) => {
  await openTasks(page)
  await page.evaluate(() => { window.__MANAGEMENT_TASK_TEST__.failList() })
  await page.getByRole('button', { name: '刷新任务' }).click()
  await expect(page.getByRole('alert')).toContainText('已显示的数据可能已过期')
  await page.getByRole('button', { name: '刷新任务' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.evaluate(() => {
    window.__MANAGEMENT_TASK_TEST__.tasks.find(t => t.id === 'task-running')!.status = 'succeeded'
    window.__MANAGEMENT_TASK_TEST__.delayDetail(500)
  })
  await expect(page.getByTestId('task-task-running')).toContainText('成功', { timeout: 8000 })
  await page.getByTestId('task-task-failed').click()
  await page.getByTestId('task-task-interrupted').click()
  await expect(page.getByTestId('task-detail')).toContainText('task-interrupted')
  await expect(page.getByTestId('task-detail')).not.toContainText('scan unavailable')
  await page.evaluate(() => { window.__MANAGEMENT_TASK_TEST__.tasks.find(t => t.id === 'task-interrupted')!.result = { result_omitted: true } })
  await page.getByRole('button', { name: '刷新任务' }).click()
  await expect(page.getByTestId('task-detail')).toContainText('结果快照过大')
})

test('keyboard navigation and English labels remain usable', async ({ page }) => {
  await openTasks(page)
  await page.getByRole('tab', { name: '后台任务' }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect(page.getByRole('tab', { name: '常用操作' })).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: '后台任务' })).toBeFocused()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.getByRole('button', { name: 'Command Center', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Background tasks' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cancel queued task' })).toBeEnabled()
  await page.evaluate(() => { window.__MANAGEMENT_TASK_TEST__.tasks.find(t => t.id === 'task-queued')!.operation = 'runtime.clear_error' })
  await page.getByRole('button', { name: 'Refresh tasks' }).click()
  await expect(page.getByTestId('task-detail')).toContainText('runtime.clear_error')
  await page.getByRole('button', { name: 'Open resource' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('lastTab'))).toBe('dashboard')
})

test('empty history, missing details and closing the panel stop polling cleanly', async ({ page }) => {
  await openTasks(page)
  await page.evaluate(() => { window.__MANAGEMENT_TASK_TEST__.tasks.splice(0) })
  await page.getByRole('button', { name: '刷新任务' }).click()
  await expect(page.getByText('暂无后台任务。')).toBeVisible()
  await expect(page.getByTestId('task-detail')).toContainText('task not found')
  await page.keyboard.press('Escape')
  // Let a pre-close request settle, then check no later polling occurs.
  await page.waitForTimeout(100)
  const count = await page.evaluate(() => window.__TAURI_BROWSER_TEST__.calls.filter(c => c.command === 'list_management_tasks').length)
  await page.waitForTimeout(3300)
  expect(await page.evaluate(() => window.__TAURI_BROWSER_TEST__.calls.filter(c => c.command === 'list_management_tasks').length)).toBe(count)
})
